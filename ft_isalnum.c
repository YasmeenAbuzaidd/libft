#include "libft.h"

int	ft_isalnum(int num)
{
	if (num >= 'a' && num <= 'z')
		return (1);
	if (num >= 'A' && num <= 'Z')
		return (1);
	if (num >= 1 && num <= 9)
		return (1);
	return (0);
}
